package com.isoform

import android.view.View
import com.facebook.react.module.annotations.ReactModule
import com.facebook.react.uimanager.ThemedReactContext
import com.facebook.react.uimanager.ViewGroupManager
import com.facebook.react.uimanager.ViewManagerDelegate
import com.facebook.react.viewmanagers.IsoModalViewManagerDelegate
import com.facebook.react.viewmanagers.IsoModalViewManagerInterface

/**
 * Bridge between Fabric and `IsoModalView`: props, events and the children, which are
 * sent to the modal's card instead of the view itself.
 * `IsoModalViewManagerInterface`/`Delegate` are generated by Codegen from
 * `src/adapters/react-native/modal/native/IsoModalViewNativeComponent.ts`.
 */
@ReactModule(name = IsoModalViewManager.NAME)
class IsoModalViewManager :
  ViewGroupManager<IsoModalView>(),
  IsoModalViewManagerInterface<IsoModalView> {

  private val delegate = IsoModalViewManagerDelegate(this)

  override fun getDelegate(): ViewManagerDelegate<IsoModalView> = delegate

  override fun getName(): String = NAME

  override fun createViewInstance(context: ThemedReactContext): IsoModalView = IsoModalView(context)

  // ── children: they live inside the card ──

  override fun addView(parent: IsoModalView, child: View, index: Int) = parent.content.addView(child, index)

  override fun getChildCount(parent: IsoModalView): Int = parent.content.childCount

  override fun getChildAt(parent: IsoModalView, index: Int): View? = parent.childAt(index)

  override fun removeViewAt(parent: IsoModalView, index: Int) = parent.content.removeViewAt(index)

  override fun removeAllViews(parent: IsoModalView) = parent.content.removeAllViews()

  // ── props ──

  override fun setOpen(view: IsoModalView, value: Boolean) { view.state.open = value }

  override fun setPresentation(view: IsoModalView, value: String?) { view.state.presentation = value ?: "dialog" }

  override fun setAnimation(view: IsoModalView, value: String?) { view.state.animation = value ?: "scale" }

  override fun setDismissible(view: IsoModalView, value: Boolean) { view.state.dismissible = value }

  override fun setBackdropColor(view: IsoModalView, value: Int?) { view.state.backdrop = value }

  override fun setSurfaceColor(view: IsoModalView, value: Int?) { view.state.surface = value }

  override fun setCornerRadius(view: IsoModalView, value: Double) { view.state.cornerRadius = value }

  override fun setMaxWidth(view: IsoModalView, value: Double) { view.state.maxWidth = value }

  override fun setContentHeight(view: IsoModalView, value: Double) { view.state.contentHeight = value }

  // ── events (native name → JS prop) ──

  override fun getExportedCustomDirectEventTypeConstants(): Map<String, Any> =
    IsoModalView.EVENTS.associateWith { mapOf("registrationName" to "on" + it.removePrefix("top")) }

  companion object {
    const val NAME = "IsoModalView"
  }
}
