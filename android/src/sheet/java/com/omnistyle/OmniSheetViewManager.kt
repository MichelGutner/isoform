package com.omnistyle

import android.view.View
import com.facebook.react.bridge.ReadableArray
import com.facebook.react.module.annotations.ReactModule
import com.facebook.react.uimanager.ThemedReactContext
import com.facebook.react.uimanager.ViewGroupManager
import com.facebook.react.uimanager.ViewManagerDelegate
import com.facebook.react.viewmanagers.OmniSheetViewManagerDelegate
import com.facebook.react.viewmanagers.OmniSheetViewManagerInterface

/**
 * Bridge between Fabric and `OmniSheetView`: props, events and the children, which
 * are sent to the sheet's content instead of the view itself.
 * `OmniSheetViewManagerInterface`/`Delegate` are generated by Codegen from
 * `src/adapters/react-native/sheet/native/OmniSheetViewNativeComponent.ts`.
 */
@ReactModule(name = OmniSheetViewManager.NAME)
class OmniSheetViewManager :
  ViewGroupManager<OmniSheetView>(),
  OmniSheetViewManagerInterface<OmniSheetView> {

  private val delegate = OmniSheetViewManagerDelegate(this)

  override fun getDelegate(): ViewManagerDelegate<OmniSheetView> = delegate

  override fun getName(): String = NAME

  override fun createViewInstance(context: ThemedReactContext): OmniSheetView = OmniSheetView(context)

  override fun onDropViewInstance(view: OmniSheetView) {
    view.release()
    super.onDropViewInstance(view)
  }

  // ── children: they live inside the sheet ──

  override fun addView(parent: OmniSheetView, child: View, index: Int) = parent.content.addView(child, index)

  override fun getChildCount(parent: OmniSheetView): Int = parent.content.childCount

  override fun getChildAt(parent: OmniSheetView, index: Int): View? = parent.childAt(index)

  override fun removeViewAt(parent: OmniSheetView, index: Int) = parent.content.removeViewAt(index)

  override fun removeAllViews(parent: OmniSheetView) = parent.content.removeAllViews()

  // ── props ──

  override fun setOpen(view: OmniSheetView, value: Boolean) = view.setOpen(value)

  override fun setDetents(view: OmniSheetView, value: ReadableArray?) = view.setDetents(value)

  override fun setDetent(view: OmniSheetView, value: Int) = view.setDetent(value)

  override fun setContentHeight(view: OmniSheetView, value: Double) = view.setContentHeight(value)

  override fun setDismissible(view: OmniSheetView, value: Boolean) = view.setDismissible(value)

  override fun setModal(view: OmniSheetView, value: Boolean) = view.setModal(value)

  override fun setGrabber(view: OmniSheetView, value: Boolean) = view.setGrabber(value)

  override fun setSheetColor(view: OmniSheetView, value: Int?) = view.setColor(value)

  override fun setCornerRadius(view: OmniSheetView, value: Double) = view.setCornerRadius(value)

  // ── events (native name → JS prop) ──

  override fun getExportedCustomDirectEventTypeConstants(): Map<String, Any> =
    OmniSheetView.EVENTS.associateWith { mapOf("registrationName" to "on" + it.removePrefix("top")) }

  companion object {
    const val NAME = "OmniSheetView"
  }
}
