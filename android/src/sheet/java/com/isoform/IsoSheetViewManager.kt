package com.isoform

import android.view.View
import com.facebook.react.bridge.ReadableArray
import com.facebook.react.module.annotations.ReactModule
import com.facebook.react.uimanager.ThemedReactContext
import com.facebook.react.uimanager.ViewGroupManager
import com.facebook.react.uimanager.ViewManagerDelegate
import com.facebook.react.viewmanagers.IsoSheetViewManagerDelegate
import com.facebook.react.viewmanagers.IsoSheetViewManagerInterface

/**
 * Bridge between Fabric and `IsoSheetView`: props, events and the children, which
 * are sent to the sheet's content instead of the view itself.
 * `IsoSheetViewManagerInterface`/`Delegate` are generated by Codegen from
 * `src/adapters/react-native/sheet/native/IsoSheetViewNativeComponent.ts`.
 */
@ReactModule(name = IsoSheetViewManager.NAME)
class IsoSheetViewManager :
  ViewGroupManager<IsoSheetView>(),
  IsoSheetViewManagerInterface<IsoSheetView> {

  private val delegate = IsoSheetViewManagerDelegate(this)

  override fun getDelegate(): ViewManagerDelegate<IsoSheetView> = delegate

  override fun getName(): String = NAME

  override fun createViewInstance(context: ThemedReactContext): IsoSheetView = IsoSheetView(context)

  override fun onDropViewInstance(view: IsoSheetView) {
    view.release()
    super.onDropViewInstance(view)
  }

  // ── children: they live inside the sheet ──

  override fun addView(parent: IsoSheetView, child: View, index: Int) = parent.content.addView(child, index)

  override fun getChildCount(parent: IsoSheetView): Int = parent.content.childCount

  override fun getChildAt(parent: IsoSheetView, index: Int): View? = parent.childAt(index)

  override fun removeViewAt(parent: IsoSheetView, index: Int) = parent.content.removeViewAt(index)

  override fun removeAllViews(parent: IsoSheetView) = parent.content.removeAllViews()

  // ── props ──

  override fun setOpen(view: IsoSheetView, value: Boolean) = view.setOpen(value)

  override fun setDetents(view: IsoSheetView, value: ReadableArray?) = view.setDetents(value)

  override fun setDetent(view: IsoSheetView, value: Int) = view.setDetent(value)

  override fun setContentHeight(view: IsoSheetView, value: Double) = view.setContentHeight(value)

  override fun setDismissible(view: IsoSheetView, value: Boolean) = view.setDismissible(value)

  override fun setModal(view: IsoSheetView, value: Boolean) = view.setModal(value)

  override fun setGrabber(view: IsoSheetView, value: Boolean) = view.setGrabber(value)

  override fun setSheetColor(view: IsoSheetView, value: Int?) = view.setColor(value)

  override fun setCornerRadius(view: IsoSheetView, value: Double) = view.setCornerRadius(value)

  // ── events (native name → JS prop) ──

  override fun getExportedCustomDirectEventTypeConstants(): Map<String, Any> =
    IsoSheetView.EVENTS.associateWith { mapOf("registrationName" to "on" + it.removePrefix("top")) }

  companion object {
    const val NAME = "IsoSheetView"
  }
}
